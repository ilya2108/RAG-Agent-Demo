def user_message(question: str, chunks: list[dict]) -> str:
    parts = [f"[{i}] {c['text']}" for i, c in enumerate(chunks, 1)]
    return "Фрагменты базы знаний:\n\n" + "\n\n".join(parts) + f"\n\nВопрос клиента: {question}"



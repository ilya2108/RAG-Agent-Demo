"""Собирает эталонные прогоны cases/<id>.json без обращения к GigaChat.

Чанки берутся из настоящего чанкера (тексты и метаданные реальные), ранги, ответы и метрики
записаны вручную по поведению пайплайна. Живые прогоны (bake.py) пишутся в cases/live/
и могут заменить эталонные: python bake.py --promote."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from clinic import prompts  # noqa: E402
from clinic.corpus import build_chunks  # noqa: E402
from clinic.metrics import gold_precision  # noqa: E402
from clinic.patients import BY_ID, public  # noqa: E402
from clinic.pipeline import DEFAULT  # noqa: E402
from clinic.settings import CASES_DIR  # noqa: E402


def S(text, ok, reason=""):
    return {"statement": text, "supported": ok, "reason": reason}


def R(ok, reason):
    return {"relevant": ok, "reason": reason}


def trace(question, cfg, chunk_specs, answer, prec, faith, rel, gold, transform=None):
    cfg = {**DEFAULT, **cfg}
    pool = {c.chunk_id: c for c in build_chunks(cfg["chunking"])}
    chunks = [{**pool[cid].to_dict(), "rank": i, "score": score} for i, (cid, score) in enumerate(chunk_specs, 1)]
    prec_verdicts = [{"id": i, **v} for i, v in enumerate(prec, 1)]
    statements = faith
    f = round(sum(s["supported"] for s in statements) / len(statements), 2) if statements else None
    p = round(sum(v["relevant"] for v in prec) / len(chunks), 2)
    g, hits = gold_precision(chunks, gold)
    return {
        "question": question, "config": cfg, "query_transform": transform or {"type": cfg["query_transform"]},
        "chunks": chunks,
        "prompt": {"system": prompts.PROMPTS[cfg["prompt"]], "user": prompts.user_message(question, chunks)},
        "answer": answer,
        "models": {"generation": "GigaChat-2-Pro", "judge": "GigaChat-2-Max", "embeddings": "Embeddings"},
        "created": "2026-10-15T12:00:00", "source": "curated",
        "metrics": {
            "precision_at_k": p, "faithfulness": f, "answer_relevance": rel["score"],
            "gold_precision_at_k": g,
            "details": {"precision": prec_verdicts, "faithfulness": statements,
                        "relevance": {"generated_questions": rel["questions"], "noncommittal": rel.get("noncommittal", 0)},
                        "gold_hits": hits},
        },
    }


def case(pid, faulty, control, fixed):
    p = BY_ID[pid]
    out = {"patient": public(p), "runs": {
        "faulty": trace(p["question"], p["faulty"], *faulty, gold=p["gold"]),
        "control": trace(p["control_question"], p["faulty"], *control, gold=p["gold_control"]),
        "fixed": trace(p["question"], p["fixed"], *fixed[:5], gold=p["gold"], transform=fixed[5] if len(fixed) > 5 else None),
    }}
    CASES_DIR.mkdir(exist_ok=True)
    (CASES_DIR / f"{pid}.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))


